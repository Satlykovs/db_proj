from dataclasses import dataclass
from decimal import Decimal

# ---------------------------------------------------------------
# 1. Структуры
# ---------------------------------------------------------------


@dataclass(frozen=True)
class CarBrandSpec:
    brand: str
    models: tuple[str, ...]
    service_spec: str
    fuel_types: tuple[str, ...]


@dataclass(frozen=True)
class ServiceSpec:
    category: str
    name: str
    base_price: Decimal
    standard_hours: Decimal
    warranty_months: int
    warranty_mileage_km: int


@dataclass(frozen=True)
class PartTemplate:
    code: str
    name: str
    min_price: int
    max_price: int


